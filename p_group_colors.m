% p_group_colors.m
% Assigns RGB colours to plankton groups for consistent plotting.
% Expects the variable 'plankton_groups_data_group' in the caller's workspace.
% Produces:
%   plankton_group_colors       : Nx3 matrix, colour per group (matched to plankton_groups_data_group)
%   plankton_group_colors_palet : 18x3 reference palette (all canonical groups)

%% Colour lookup table  [group_name, R, G, B]
lut = { ...
    'bacillariophyta',  0.10, 0.61, 0.46; ...
    'chaetognatha',     0.69, 0.84, 0.88; ...
    'ciliophora',       0.79, 0.77, 1.00; ...
    'cnidaria',         0.41, 0.60, 0.78; ...
    'nanoplankton',     0.40, 0.56, 0.23; ...
    'copepoda',         0.91, 0.56, 0.42; ...
    'crustacea',        0.93, 0.69, 0.13; ...
    'cyanobacteria',    0.44, 0.59, 0.65; ...
    'detritus',         0.95, 0.95, 0.95; ...
    'dictyochophyceae', 0.89, 0.90, 0.59; ...
    'dinoflagellata',   0.71, 0.83, 0.58; ...
    'mollusca',         0.78, 0.51, 0.51; ...
    'other',            0.98, 0.98, 0.73; ...
    'unidentified',     1.00, 0.93, 0.81; ...
    'plastics',         0.00, 0.45, 0.74; ...
    'rhizaria',         0.98, 0.83, 0.92; ...
    'tunicata',         0.23, 0.39, 0.54; ...
    'ctenophora',       0.85, 0.90, 0.95  ...
};

%% Per-group colours matched to plankton_groups_data_group
plankton_group_colors = repmat([0.8 0.8 0.8], numel(plankton_groups_data_group), 1);

for k = 1:numel(plankton_groups_data_group)
    row = find(strcmp(strtrim(plankton_groups_data_group{k}), lut(:,1)), 1);
    if ~isempty(row)
        plankton_group_colors(k,:) = [lut{row,2}, lut{row,3}, lut{row,4}];
    end
end

%% Full reference palette (all 18 canonical groups, in order)
plankton_group_colors_palet = cell2mat(lut(:, 2:4));
